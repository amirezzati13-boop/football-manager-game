const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'app.js'),'utf8');
assert.match(app,/function recordFinance\(type,amount,note,meta=\{\}\)/,'central ledger helper exists');
assert.match(app,/state\.financeLedger\.unshift\(/,'transactions are newest-first');
assert.match(app,/state\.financeLedger=state\.financeLedger\.slice\(0,100\)/,'ledger is bounded to 100 entries');
assert.match(app,/recordFinance\('income_ticket'/,'ticket receipts are logged');
assert.match(app,/recordFinance\('expense_wages_accrued'/,'wage accrual is distinguished from payment');
assert.match(app,/recordFinance\('expense_wages_paid'/,'actual wage settlement is logged');
assert.match(app,/recordFinance\('expense_operating'/,'operating costs are logged');
assert.match(app,/recordFinance\('income_sponsor'/,'sponsor income is logged');
assert.match(app,/recordFinance\('income_prize'/,'league prize income is logged');
assert.match(app,/recordFinance\('spend_gold'/,'premium currency spending is logged separately');
assert.match(app,/دفتر تراکنش‌های مالی/,'finance UI exposes ledger');
