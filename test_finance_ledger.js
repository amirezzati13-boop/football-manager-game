const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);assert.equal(scripts[0][1],app,'inline script stays synced');
console.log('PASS finance ledger: bounded transaction log, income/expense/accrual separation, gold currency and synced UI');
