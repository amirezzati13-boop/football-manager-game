const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.match(app,/function playerValue\(p\)/,'market value must be computed from a shared player valuation function');
assert.match(app,/function buyPlayer\(id\)/,'player acquisition flow must exist');
assert.match(app,/function sellPlayer\(id\)/,'player sale flow must exist');
assert.match(app,/function loanPlayer\(id\)/,'loan flow must exist');
assert.match(app,/state\.transferRestricted\|\|state\.squad\.length>=32\|\|!canSpend\(p\.fee\)/,'purchase must enforce transfer restrictions, squad cap, and available cash');
assert.match(app,/const skill=\(p,keys\)=>keys\.reduce/,'trained attributes must be safely bounded before use');
assert.match(app,/skill\(p,\['speed','control','shooting'\]\)\*1\.5/,'speed/control/shooting must influence attacking performance');
assert.match(app,/skill\(p,\['defending','strength'\]\)\*1\.25/,'defending/strength must influence defensive performance');
assert.match(app,/skill\(p,\['passing','decisions','stamina'\]\)\*\.75/,'passing/decisions/stamina must influence midfield performance');
assert.match(app,/skill\(p,\['decisions','strength'\]\)\*1\.1/,'trained goalkeeper-related skills must influence keeper profile');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'exactly one inline app script expected');
assert.equal(scripts[0][1],app,'inline app script must remain in sync with app.js');
console.log('PASS player attributes and transfer safety: trained skills affect match profiles, transfer guards remain, app bundle synced');
